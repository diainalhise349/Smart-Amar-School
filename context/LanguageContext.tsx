export const toBengaliNumber = (num: number | string): string => {
  const bnDigits = ['০', '১', '২', '৩', '৪', '৫', '৬', '৭', '৮', '৯'];
  return String(num).replace(/[0-9]/g, (d) => bnDigits[parseInt(d, 10)]);
};

export interface LanguageContextType {
  language: LanguageCode;
  currentLanguage: LanguageCode;
  setLanguage: (lang: LanguageCode) => void;
  toggleLanguage: () => void;
  toggleBengaliEnglish: () => void;
  isBengali: boolean;
  isEnglish: boolean;
  t: (key: string, fallback?: string) => string;
  isRTL: boolean;
  formatNumber: (num: number | string) => string;
}

const LanguageContext = createContext<LanguageContextType | undefined>(undefined);

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<LanguageCode>(() => {
    try {
      const stored = localStorage.getItem('app_lang') || localStorage.getItem('smart_school_lang');
      return (stored as LanguageCode) || 'en';
    } catch {
      return 'en';
    }
  });

  const isRTL = language === 'ar' || language === 'ur';
  const isBengali = language === 'bn';
  const isEnglish = language === 'en';

  const setLanguage = (newLang: LanguageCode) => {
    setLanguageState(newLang);
    try {
      localStorage.setItem('app_lang', newLang);
      localStorage.setItem('smart_school_lang', newLang);
      window.dispatchEvent(new CustomEvent('languagechange', { detail: { language: newLang } }));
    } catch {
      // ignore storage errors
    }
  };

  const toggleLanguage = () => {
    setLanguage(language === 'bn' ? 'en' : 'bn');
  };

  const toggleBengaliEnglish = toggleLanguage;

  useEffect(() => {
    try {
      localStorage.setItem('app_lang', language);
      localStorage.setItem('smart_school_lang', language);
    } catch {
      // ignore storage errors
    }
    document.documentElement.dir = isRTL ? 'rtl' : 'ltr';
    document.documentElement.lang = language;
  }, [language, isRTL]);

  const t = (key: string, fallback?: string): string => {
    if (!key) return fallback || '';
    const langDict = TRANSLATIONS[language];
    if (langDict && langDict[key]) {
      return langDict[key];
    }
    if (TRANSLATIONS['en'] && TRANSLATIONS['en'][key]) {
      return TRANSLATIONS['en'][key];
    }
    return fallback !== undefined ? fallback : key;
  };

  const formatNumber = (num: number | string): string => {
    if (language !== 'bn') return String(num);
    return toBengaliNumber(num);
  };

  return (
    <LanguageContext.Provider
      value={{
        language,
        currentLanguage: language,
        setLanguage,
        toggleLanguage,
        toggleBengaliEnglish,
        isBengali,
        isEnglish,
        t,
        isRTL,
        formatNumber
      }}
    >
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => {
  const context = useContext(LanguageContext);
  if (context === undefined) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
};

